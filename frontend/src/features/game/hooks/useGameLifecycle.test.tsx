import { act, renderHook, waitFor } from '@testing-library/react'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import * as api from '../../../api/game'
import { ApiError } from '../../../api/client'
import useGameLifecycle from './useGameLifecycle'

vi.mock('../../../api/game')
const lives: api.GameLives = { availableLives: 3, maxLives: 3, nextRechargeAt: null, serverTime: '2026-10-18T10:00:00Z' }
const session: api.GameSession = {
  sessionId: 'real-server-session', status: 'ACTIVE', startedAt: lives.serverTime,
  expiresAt: '2026-10-18T10:15:00Z', engineVersion: 'v1', remainingLives: 2,
  nextRechargeAt: '2026-10-18T12:00:00Z', serverTime: lives.serverTime,
}
const accepted: api.AcceptedScore = { scoreId: 'real-server-score', sessionId: session.sessionId, score: 50, acceptedAt: '2026-10-18T10:00:10Z', sessionStatus: 'COMPLETED' }
function deferred<T>() {
  let resolve!: (value: T) => void
  const promise = new Promise<T>(done => { resolve = done })
  return { promise, resolve }
}
async function ready() {
  const hook = renderHook(() => useGameLifecycle())
  await waitFor(() => expect(hook.result.current.lives.status).toBe('ready'))
  return hook
}
beforeEach(() => {
  vi.resetAllMocks()
  vi.mocked(api.getGameLives).mockResolvedValue({ ...lives })
  vi.mocked(api.getGameSummary).mockResolvedValue({ personalBest: 10 })
  vi.mocked(api.startGameSession).mockResolvedValue({ ...session })
  vi.mocked(api.getGameSession).mockResolvedValue({ ...session })
  vi.mocked(api.submitGameScore).mockResolvedValue({ ...accepted })
  vi.mocked(api.getAcceptedScore).mockResolvedValue({ ...accepted })
})

describe('server-owned game lifecycle', () => {
  it('loads lives and personal best, and blocks start until lives load', async () => {
    const pending = deferred<api.GameLives>()
    vi.mocked(api.getGameLives).mockReturnValue(pending.promise)
    const { result } = renderHook(() => useGameLifecycle())
    expect(result.current.canStart).toBe(false)
    await act(async () => result.current.begin())
    expect(api.startGameSession).not.toHaveBeenCalled()
    await act(async () => pending.resolve(lives))
    expect(result.current.canStart).toBe(true)
    expect(result.current.best).toBe(10)
  })
  it('zero lives prevent start and display the server recharge countdown', async () => {
    vi.mocked(api.getGameLives).mockResolvedValue({ ...lives, availableLives: 0, nextRechargeAt: '2026-10-18T12:00:00Z' })
    const { result } = await ready()
    expect(result.current.canStart).toBe(false)
    expect(result.current.lives.countdown).toMatch(/^0[12]:/)
    await act(async () => result.current.begin())
    expect(api.startGameSession).not.toHaveBeenCalled()
  })
  it('waits for exactly one successful start before playing and applies server remaining lives', async () => {
    const pending = deferred<api.GameSession>()
    vi.mocked(api.startGameSession).mockReturnValue(pending.promise)
    const { result } = await ready()
    let action!: Promise<void>
    act(() => { action = result.current.begin(); void result.current.begin() })
    expect(result.current.phase).toBe('idle')
    expect(result.current.canStart).toBe(false)
    expect(api.startGameSession).toHaveBeenCalledTimes(1)
    expect(api.startGameSession).toHaveBeenCalledWith(expect.stringMatching(/^[0-9a-f-]{36}$/))
    await act(async () => { pending.resolve(session); await action })
    expect(result.current.phase).toBe('playing')
    expect(result.current.lives.data?.availableLives).toBe(2)
    expect(api.getGameLives).toHaveBeenCalledTimes(1)
  })
  it('network failure never starts a run and retry reuses its key with owned recovery', async () => {
    vi.mocked(api.startGameSession).mockRejectedValueOnce(new TypeError('Network failure')).mockResolvedValueOnce(session)
    const { result } = await ready()
    await act(async () => result.current.begin())
    expect(result.current.phase).toBe('idle'); expect(result.current.lives.data?.availableLives).toBe(3)
    expect(result.current.startStatus).toBe('failed')
    await act(async () => result.current.begin())
    expect(vi.mocked(api.startGameSession).mock.calls[0][0]).toBe(vi.mocked(api.startGameSession).mock.calls[1][0])
    expect(api.getGameSession).toHaveBeenCalledWith(session.sessionId)
    expect(result.current.phase).toBe('playing')
  })
  it('does not replay an expired ACTIVE creation snapshot as a new run', async () => {
    vi.mocked(api.startGameSession).mockRejectedValueOnce(new Error('Lost response')).mockResolvedValue(session)
    vi.mocked(api.getGameSession).mockResolvedValue({ ...session, status: 'EXPIRED' })
    const { result } = await ready()
    await act(async () => result.current.begin())
    await act(async () => result.current.begin())
    expect(result.current.phase).toBe('idle'); expect(result.current.error).toMatch(/expired/)
    expect(result.current.lives.data?.availableLives).toBe(2)
  })
  it('preserves an ambiguous start key even if a background GET now shows zero lives', async () => {
    vi.mocked(api.startGameSession).mockRejectedValueOnce(new Error('Lost response')).mockResolvedValue(session)
    const { result } = await ready()
    await act(async () => result.current.begin())
    vi.mocked(api.getGameLives).mockResolvedValue({ ...lives, availableLives: 0 })
    await act(async () => result.current.lives.refresh())
    expect(result.current.canStart).toBe(true)
    await act(async () => result.current.begin())
    expect(result.current.phase).toBe('playing')
  })
  it.each(['NO_GAME_LIVES', 'GAME_SESSION_ACTIVE'])('handles %s without granting or consuming lives locally', async code => {
    vi.mocked(api.startGameSession).mockRejectedValue(new ApiError(409, { code }))
    vi.mocked(api.getGameLives).mockResolvedValueOnce(lives).mockResolvedValueOnce({ ...lives, availableLives: code === 'NO_GAME_LIVES' ? 0 : 3 })
    const { result } = await ready()
    await act(async () => result.current.begin())
    expect(result.current.phase).toBe('idle'); expect(result.current.error).not.toBe('')
    expect(result.current.canStart).toBe(false)
    expect(api.startGameSession).toHaveBeenCalledTimes(1)
  })
  it('failed lives loading never assumes three lives; retry can recover', async () => {
    vi.mocked(api.getGameLives).mockRejectedValueOnce(new Error('offline'))
    const { result } = renderHook(() => useGameLifecycle())
    await waitFor(() => expect(result.current.lives.status).toBe('error'))
    expect(result.current.lives.data).toBeNull(); expect(result.current.canStart).toBe(false)
    await act(async () => result.current.lives.refresh())
    expect(result.current.canStart).toBe(true)
  })
  it('personal-best failure does not block playing with loaded lives', async () => {
    vi.mocked(api.getGameSummary).mockRejectedValue(new Error('summary offline'))
    const { result } = await ready()
    expect(result.current.best).toBeNull(); expect(result.current.summaryError).not.toBe('')
    await act(async () => result.current.begin())
    expect(result.current.phase).toBe('playing')
  })
  it('a late lives GET cannot overwrite newer session-start data', async () => {
    vi.mocked(api.startGameSession).mockRejectedValueOnce(new Error('Lost response')).mockResolvedValue(session)
    const { result } = await ready()
    await act(async () => result.current.begin())
    const pending = deferred<api.GameLives>()
    vi.mocked(api.getGameLives).mockReturnValue(pending.promise)
    let refresh!: Promise<void>
    act(() => { refresh = result.current.lives.refresh() })
    await act(async () => result.current.begin())
    expect(result.current.lives.data?.availableLives).toBe(2)
    await act(async () => { pending.resolve(lives); await refresh })
    expect(result.current.lives.data?.availableLives).toBe(2)
  })
  it('submits one frozen game-over score and key despite repeated callbacks', async () => {
    const pending = deferred<api.AcceptedScore>()
    vi.mocked(api.submitGameScore).mockReturnValue(pending.promise)
    const { result } = await ready()
    await act(async () => result.current.begin())
    act(() => { result.current.finish(50); result.current.finish(999) })
    expect(result.current.phase).toBe('gameover'); expect(result.current.finalScore).toBe(50)
    expect(result.current.submissionStatus).toBe('pending'); expect(api.submitGameScore).toHaveBeenCalledTimes(1)
    expect(api.submitGameScore).toHaveBeenCalledWith(session.sessionId, 50, expect.stringMatching(/^[0-9a-f-]{36}$/))
    vi.mocked(api.getGameSummary).mockResolvedValue({ personalBest: 50 })
    await act(async () => pending.resolve(accepted))
    await waitFor(() => expect(result.current.submissionStatus).toBe('accepted'))
    expect(result.current.accepted?.score).toBe(50); expect(result.current.best).toBe(50)
    expect(result.current.newBest).toBe(true)
  })
  it('slow optional summary refresh cannot block another deliberate run after acceptance', async () => {
    const { result } = await ready()
    await act(async () => result.current.begin())
    const summary = deferred<api.GameSummary>()
    vi.mocked(api.getGameSummary).mockReturnValue(summary.promise)
    await act(async () => result.current.finish(50))
    await waitFor(() => expect(result.current.submissionStatus).toBe('accepted'))
    act(() => result.current.returnToPreview())
    expect(result.current.phase).toBe('idle')
    await act(async () => result.current.begin())
    expect(api.startGameSession).toHaveBeenCalledTimes(2)
    expect(result.current.phase).toBe('playing')
    await act(async () => summary.resolve({ personalBest: 50 }))
  })
  it('score retry uses the same key and original score after an ambiguous failure', async () => {
    vi.mocked(api.submitGameScore).mockRejectedValueOnce(new Error('timeout')).mockResolvedValue(accepted)
    const { result } = await ready()
    await act(async () => result.current.begin())
    await act(async () => result.current.finish(50))
    await waitFor(() => expect(result.current.submissionStatus).toBe('failed'))
    await act(async () => result.current.retryScore())
    expect(vi.mocked(api.submitGameScore).mock.calls[0]).toEqual(vi.mocked(api.submitGameScore).mock.calls[1])
    expect(result.current.submissionStatus).toBe('accepted')
  })
  it.each(['SCORE_IMPLAUSIBLE', 'SESSION_EXPIRED'])('handles %s safely without refunds', async code => {
    vi.mocked(api.submitGameScore).mockRejectedValue(new ApiError(409, { code, detail: 'private formula internals' }))
    const { result } = await ready()
    await act(async () => result.current.begin())
    vi.mocked(api.getGameLives).mockResolvedValue({ ...lives, availableLives: 2 })
    await act(async () => result.current.finish(50))
    await waitFor(() => expect(result.current.submissionStatus).toBe('rejected'))
    expect(result.current.error).not.toContain('formula'); expect(result.current.accepted).toBeNull()
    expect(result.current.lives.data?.availableLives).toBe(2)
  })
  it('recovers the existing accepted result on a different-score conflict without changing the frozen run', async () => {
    vi.mocked(api.submitGameScore).mockRejectedValue(new ApiError(409, { code: 'SCORE_ALREADY_SUBMITTED' }))
    vi.mocked(api.getAcceptedScore).mockResolvedValue({ ...accepted, score: 20 })
    const { result } = await ready()
    await act(async () => result.current.begin())
    await act(async () => result.current.finish(50))
    await waitFor(() => expect(result.current.accepted?.score).toBe(20))
    expect(result.current.finalScore).toBe(50)
    expect(api.submitGameScore).toHaveBeenCalledTimes(1)
  })
  it.each([401, 403])('handles HTTP %s without starting locally', async status => {
    vi.mocked(api.startGameSession).mockRejectedValue(new ApiError(status))
    const { result } = await ready()
    await act(async () => result.current.begin())
    expect(result.current.phase).toBe('idle'); expect(result.current.error).not.toBe('')
  })
  it('unmounting does not refund, persist lives or start a late successful run', async () => {
    const pending = deferred<api.GameSession>(); vi.mocked(api.startGameSession).mockReturnValue(pending.promise)
    const storage = vi.spyOn(Storage.prototype, 'setItem')
    const { result, unmount } = await ready()
    let start!: Promise<void>
    act(() => { start = result.current.begin() })
    unmount()
    await act(async () => { pending.resolve(session); await start })
    expect(result.current.phase).toBe('idle'); expect(storage).not.toHaveBeenCalled()
    expect(api.getGameLives).toHaveBeenCalledTimes(1)
  })
})

describe('display-only recharge and Retry-After', () => {
  beforeEach(() => vi.useFakeTimers({ toFake: ['setInterval', 'clearInterval', 'setTimeout', 'clearTimeout', 'performance'] }))
  it('countdown zero refetches instead of adding a life itself', async () => {
    const pending = deferred<api.GameLives>()
    vi.mocked(api.getGameLives).mockResolvedValueOnce({ ...lives, availableLives: 0, nextRechargeAt: '2026-10-18T10:00:01Z' }).mockReturnValueOnce(pending.promise)
    const { result } = renderHook(() => useGameLifecycle())
    await act(async () => { await Promise.resolve() })
    expect(result.current.lives.data?.availableLives).toBe(0)
    await act(async () => vi.advanceTimersByTimeAsync(1100))
    expect(api.getGameLives).toHaveBeenCalledTimes(2)
    expect(result.current.lives.data?.availableLives).toBe(0)
    await act(async () => pending.resolve({ ...lives, availableLives: 1 }))
    expect(result.current.lives.data?.availableLives).toBe(1)
  })
  it('device wall-clock changes do not grant lives or alter the server-anchored countdown', async () => {
    vi.spyOn(Date, 'now').mockReturnValue(9_000_000_000_000)
    vi.mocked(api.getGameLives).mockResolvedValue({ ...lives, availableLives: 0, nextRechargeAt: '2026-10-18T12:00:00Z' })
    const { result } = renderHook(() => useGameLifecycle())
    await act(async () => { await Promise.resolve() })
    expect(result.current.lives.countdown).toBe('02:00:00')
    expect(result.current.lives.data?.availableLives).toBe(0)
  })
  it('score throttling retains the frozen score/key and prevents early retries', async () => {
    vi.mocked(api.submitGameScore).mockRejectedValueOnce(new ApiError(429, { code: 'RATE_LIMITED' }, 5)).mockResolvedValue(accepted)
    const { result } = renderHook(() => useGameLifecycle())
    await act(async () => { await Promise.resolve() })
    await act(async () => result.current.begin())
    await act(async () => result.current.finish(50))
    expect(result.current.submissionStatus).toBe('failed')
    await act(async () => result.current.retryScore())
    expect(api.submitGameScore).toHaveBeenCalledTimes(1)
    await act(async () => vi.advanceTimersByTimeAsync(5000))
    await act(async () => result.current.retryScore())
    expect(vi.mocked(api.submitGameScore).mock.calls[0]).toEqual(vi.mocked(api.submitGameScore).mock.calls[1])
    expect(result.current.submissionStatus).toBe('accepted')
  })
  it('respects Retry-After and retains the same start key', async () => {
    vi.mocked(api.startGameSession).mockRejectedValueOnce(new ApiError(429, { code: 'RATE_LIMITED' }, 5)).mockResolvedValue(session)
    const { result } = renderHook(() => useGameLifecycle())
    await act(async () => { await Promise.resolve() })
    await act(async () => result.current.begin())
    expect(result.current.canStart).toBe(false)
    await act(async () => result.current.begin())
    expect(api.startGameSession).toHaveBeenCalledTimes(1)
    await act(async () => vi.advanceTimersByTimeAsync(5000))
    expect(result.current.canStart).toBe(true)
    await act(async () => result.current.begin())
    expect(vi.mocked(api.startGameSession).mock.calls[0][0]).toBe(vi.mocked(api.startGameSession).mock.calls[1][0])
  })
})
